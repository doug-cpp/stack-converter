def resolve_target_stack(target_input: str | None) -> TargetStackSpec:
    """Resolve a target stack identifier or alias against TARGET_STACK_REGISTRY."""
    if not target_input:
        return TARGET_STACK_REGISTRY["typescript-node"]
    normalized = target_input.strip().lower()
    for spec in TARGET_STACK_REGISTRY.values():
        if normalized == spec.id or normalized in spec.aliases:
            if spec.status != TargetStackStatus.AVAILABLE:
                available_ids = [
                    s.id for s in TARGET_STACK_REGISTRY.values() if s.status == TargetStackStatus.AVAILABLE
                ]
                raise ValueError(
                    f"Target output stack '{spec.id}' ({spec.display_name}) is registered as '{spec.status.value}' "
                    f"in the extensible catalog, but only {available_ids} is enabled in this PoC."
                )
            return spec
    available_ids = [
        f"{s.id} (aliases: {', '.join(s.aliases)})"
        for s in TARGET_STACK_REGISTRY.values()
        if s.status == TargetStackStatus.AVAILABLE
    ]
    raise ValueError(
        f"Unknown target output stack '{target_input}'. Available PoC target stack(s): {', '.join(available_ids)}."
    )


class LibMapStatus(StrEnum):
    """Mapping status of a Python dependency in TypeScript/Node.js."""

    STDLIB = "stdlib"
    MAPPED = "mapped"
    UNSUPPORTED = "unsupported"
    UNMAPPED = "unmapped"


class LibMapEntry(StrictModel):
    """Mapping rule connecting a Python module/package to a TypeScript equivalent."""

    python_package: str
    ts_equivalent: str | None = None
    npm_package: str | None = None
    status: LibMapStatus
    notes: str = ""


class CycleGroup(StrictModel):
    """Group of mutually dependent modules collapsed into a super-node."""

    group_id: str
    modules: list[str]


class MigrationPlan(StrictModel):
    """Topological migration plan and resolved dependency mapping."""

    levels: list[list[str]] = Field(
        ..., description="Ordered topological levels from leaf modules (level 0) to entry points"
    )
    cycles: list[CycleGroup] = Field(default_factory=list)
    library_mappings: list[LibMapEntry] = Field(default_factory=list)
    source_stack: str = "python"
    target_stack: str = "typescript-node"
    target_language: str = "typescript"


