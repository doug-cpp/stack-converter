"""Shared Pydantic v2 data contracts for the StackConverter pipeline."""

from __future__ import annotations

from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class StrictModel(BaseModel):
    """Base model with strict extra field prohibition."""

    model_config = ConfigDict(extra="forbid")


# ---------------------------------------------------------------------------
# 1. Graph Contracts
# ---------------------------------------------------------------------------


class NodeType(StrEnum):
    """Supported structural node types in the codebase graph."""

    MODULE = "module"
    CLASS = "class"
    FUNCTION = "function"
    EXTERNAL_PACKAGE = "external_package"


class EdgeType(StrEnum):
    """Supported structural relationship types in the codebase graph."""

    IMPORTS = "imports"
    CALLS = "calls"
    DEFINES = "defines"
    INHERITS = "inherits"


class ParameterInfo(StrictModel):
    """Function or method parameter metadata extracted from Python AST."""

    name: str
    annotation: str | None = None
    default: str | None = None


class Node(StrictModel):
    """A structural node in the normalized codebase graph."""

    id: str = Field(..., description="Unique deterministic identifier, e.g., module.submodule or module:func")
    name: str = Field(..., description="Short symbol or module name")
    node_type: NodeType
    file_path: str | None = Field(default=None, description="Relative path from source root")
    line_start: int | None = Field(default=None, ge=1)
    line_end: int | None = Field(default=None, ge=1)
    signature: str | None = Field(default=None, description="Function or class signature if applicable")
    parameters: list[ParameterInfo] = Field(default_factory=list)
    return_annotation: str | None = None
    is_public: bool = True
    docstring: str | None = None
    source_code: str | None = None
    imports: list[str] = Field(default_factory=list, description="Imported module/package names")


class Edge(StrictModel):
    """A directed relationship between two nodes in the codebase graph."""

    source: str = Field(..., description="Source node ID")
    target: str = Field(..., description="Target node ID")
    edge_type: EdgeType
    line: int | None = Field(default=None, ge=1)


class CodeGraph(StrictModel):
    """Normalized codebase graph produced by graphify + Python AST enrichment."""

    source_root: str
    nodes: list[Node] = Field(default_factory=list)
    edges: list[Edge] = Field(default_factory=list)

    def get_node(self, node_id: str) -> Node | None:
        """Return a node by ID, or None if not found."""
        for node in self.nodes:
            if node.id == node_id:
                return node
        return None

    def module_nodes(self) -> list[Node]:
        """Return all internal module nodes sorted by ID."""
        return sorted(
            [n for n in self.nodes if n.node_type == NodeType.MODULE],
            key=lambda n: n.id,
        )


