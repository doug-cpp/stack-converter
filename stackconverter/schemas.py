class CharacterizationCase(StrictModel):
    """A single recorded input/output oracle case for a public function."""

    function_name: str
    args: list[Any] = Field(default_factory=list)
    kwargs: dict[str, Any] = Field(default_factory=dict)
    expected_output: Any = None
    raises_exception: str | None = None


class CharacterizationProposal(StrictModel):
    """LLM-proposed test inputs for public functions in a module."""

    module_id: str
    cases: list[CharacterizationCase] = Field(default_factory=list)


class CharacterizationSuite(StrictModel):
    """Recorded real Python input/output characterization suite for a module."""

    module_id: str
    file_path: str
    cases: list[CharacterizationCase] = Field(default_factory=list)


