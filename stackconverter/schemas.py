# 6. Code Generation, Validation & Reporting Contracts
# ---------------------------------------------------------------------------


class ModuleConversionStatus(StrEnum):
    """Final conversion status of an individual module."""

    CONVERTED = "converted"
    PENDING = "pending"
    SKIPPED = "skipped"


class ModuleCode(StrictModel):
    """Generated or fixed TypeScript code for a single module."""

    module_id: str
    target_path: str = Field(..., description="Relative path inside output_ts/src/, e.g. src/math_utils.ts")
    typescript_code: str
    exported_signatures: list[str] = Field(
        default_factory=list,
        description="Exported TypeScript function/class/type declarations for downstream context",
    )
    notes: str = ""


class ValidationDiagnostic(StrictModel):
    """Single compiler, linter, or characterization test diagnostic."""

    source: str = Field(..., description="tsc | eslint | characterization")
    file_path: str | None = None
    line: int | None = None
    column: int | None = None
    code: str | None = None
    message: str


class ValidationResult(StrictModel):
    """Aggregated validation outcome for a module attempt."""

    module_id: str
    attempt: int = Field(..., ge=1)
    tsc_passed: bool
    eslint_passed: bool
    characterization_passed: bool
    characterization_total: int = 0
    characterization_matched: int = 0
    diagnostics: list[ValidationDiagnostic] = Field(default_factory=list)

    @property
    def passed(self) -> bool:
        """Return True if all deterministic checks passed."""
        return self.tsc_passed and self.eslint_passed and self.characterization_passed


class ModuleReportEntry(StrictModel):
    """Summary of conversion and validation results for a module."""

    module_id: str
    source_path: str
    target_path: str
    level: int
    status: ModuleConversionStatus
    attempts: int
    tsc_passed: bool
    eslint_passed: bool
    characterization_passed: bool
    diagnostics: list[ValidationDiagnostic] = Field(default_factory=list)


class RunMetrics(StrictModel):
    """Execution metrics and summary statistics for the final report."""

    run_id: str
    source_root: str
    source_stack: str = "python"
    target_stack: str = "typescript-node"
    verdict: VerdictType
    total_modules: int = 0
    converted_modules: int = 0
    pending_modules: int = 0
    total_characterization_cases: int = 0
    passed_characterization_cases: int = 0
    cache_hits: int = 0
    llm_calls: int = 0
    module_entries: list[ModuleReportEntry] = Field(default_factory=list)

